from sqlalchemy import Boolean, Column, Float, Integer, String
from app.core.tenant_database import Base

class GuiaTipo(Base):
    __tablename__ = "tte_guia_tipo"

    codigo_guia_tipo_pk = Column(String(20), primary_key=True, index=True)
    nombre = Column(String(100), nullable=True)
    factura = Column(Boolean, nullable=True, default=False)
    contado = Column(Boolean, nullable=True, default=False)
    destino = Column(Boolean, nullable=True, default=False)
    corriente = Column(Boolean, nullable=True, default=False)
    cortesia = Column(Boolean, nullable=True, default=False)
    importar_excel = Column(Boolean, nullable=True, default=False)
    consecutivo = Column(Integer, nullable=True, default=0)
    consecutivo_factura = Column(Integer, nullable=True, default=0)
    codigo_factura_tipo_fk = Column(String(20), nullable=True)
    exige_numero = Column(Boolean, nullable=True, default=False)
    orden = Column(Integer, nullable=True, default=0)
    validar_flete = Column(Boolean, nullable=True, default=False)
    validar_rango = Column(Boolean, nullable=True, default=False)
    estado_inactivo = Column(Boolean, nullable=True, default=False)
    estado_inactivo_portal = Column(Boolean, nullable=False, default=False)
    validar_caracteres = Column(Integer, nullable=True)
    codigo_pago_fk = Column(String(3), nullable=True)
    codigo_forma_pago = Column(String(3), nullable=True)
    mensaje_formato = Column(String(900), nullable=True)
    vr_tope = Column(Float, nullable=False, default=0.0)
    enviar_rndc = Column(Boolean, nullable=True, default=False)
    tipo_guia_rndc = Column(String(3), nullable=False, default="NAC")
    genera_cobro = Column(Boolean, nullable=True, default=False)
    genera_cobro_entrega = Column(Boolean, nullable=True, default=False)
    asignar_consecutivo_factura = Column(Boolean, nullable=False, default=True)
    codigo_comprobante_fk = Column(String(20), nullable=True)
    codigo_cuenta_cliente_fk = Column(String(20), nullable=True)
    codigo_cuenta_flete_fk = Column(String(20), nullable=True)
    codigo_cuenta_manejo_fk = Column(String(20), nullable=True)
    codigo_cuenta_reexpedicion_fk = Column(String(20), nullable=True)
    cotizacion = Column(Boolean, nullable=False, default=False)
    codigo_empresa_fk = Column(Integer, nullable=False)
