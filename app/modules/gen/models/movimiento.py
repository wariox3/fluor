from sqlalchemy import Column, Integer, String, Boolean, DateTime, Date, Float, SmallInteger, Text, ForeignKey
from sqlalchemy.ext.hybrid import hybrid_property
from app.core.tenant_database import Base
from sqlalchemy.orm import relationship
from datetime import datetime
from app.modules.gen.models.tercero import Tercero

class Movimiento(Base):
    __tablename__ = "gen_movimiento"

    codigo_movimiento_pk = Column(Integer, primary_key=True, index=True)
    codigo_movimiento_tipo_fk = Column(String(10), nullable=False)
    codigo_forma_pago_fk = Column(String(10), nullable=True)
    codigo_asesor_fk = Column(Integer, nullable=True)
    codigo_movimiento_clase_fk = Column(String(10), nullable=False)
    codigo_sucursal_fk = Column(Integer, nullable=True)
    codigo_movimiento_fk = Column(Integer, nullable=True)
    prefijo = Column(String(5), nullable=True)
    numero = Column(Integer, nullable=True, default=0)
    direccion = Column(String(100), nullable=True)
    fecha = Column(DateTime, nullable=True)
    fecha_documento = Column(Date, nullable=True)
    fecha_vence = Column(Date, nullable=True)
    fecha_electronico = Column(DateTime, nullable=True)
    fecha_entrega = Column(DateTime, nullable=True)
    plazo_pago = Column(Integer, nullable=True, default=0)
    vr_flete = Column(Float, nullable=False, default=0.0)
    vr_manejo = Column(Float, nullable=False, default=0.0)
    codigo_tercero_fk = Column(Integer, ForeignKey("gen_tercero.codigo_tercero_pk"), nullable=True)
    codigo_tercero_destino_fk = Column(Integer, nullable=True)
    codigo_contacto_fk = Column(Integer, nullable=True)
    soporte = Column(String(100), nullable=True)
    orden_compra = Column(String(50), nullable=True)
    orden_ingreso = Column(String(50), nullable=True)
    remision = Column(String(50), nullable=True)
    vr_base_iva = Column(Float, nullable=True, default=0.0)
    vr_iva = Column(Float, nullable=True, default=0.0)
    vr_base_aiu = Column(Float, nullable=True, default=0.0)
    vr_subtotal_bruto = Column(Float, nullable=False, default=0.0)
    vr_subtotal = Column(Float, nullable=False, default=0.0)
    vr_descuento = Column(Float, nullable=False, default=0.0)
    vr_neto = Column(Float, nullable=False, default=0.0)
    vr_total = Column(Float, nullable=False, default=0.0)
    vr_retencion_fuente = Column(Float, nullable=False, default=0.0)
    vr_retencion_iva = Column(Float, nullable=False, default=0.0)
    vr_autoretencion = Column(Float, nullable=False, default=0.0)
    vr_retencion_industria_comercio = Column(Float, nullable=False, default=0.0)
    vr_anticipo = Column(Float, nullable=False, default=0.0)
    comentarios = Column(String(500), nullable=True)
    usuario = Column(String(25), nullable=True)
    fecha_aprobado = Column(DateTime, nullable=True)
    usuario_aprobado = Column(String(25), nullable=True)
    usuario_externo = Column(String(50), nullable=True)
    estado_autorizado = Column(Boolean, nullable=False, default=False)
    estado_aprobado = Column(Boolean, nullable=False, default=False)
    estado_anulado = Column(Boolean, nullable=False, default=False)
    estado_contabilizado = Column(Boolean, nullable=False, default=False)
    estado_generado = Column(Boolean, nullable=True, default=False)
    estado_electronico = Column(Boolean, nullable=True, default=False)
    estado_descartado_electronico = Column(Boolean, nullable=True, default=False)
    estado_notificado_electronico = Column(Boolean, nullable=True, default=False)
    respuesta_electronico = Column(String(3), nullable=True, default="P")
    respuesta_electronico_fecha = Column(DateTime, nullable=True)
    proceso_factura_electronica = Column(String(2), nullable=True)
    operacion_inventario = Column(SmallInteger, nullable=True, default=0)
    operacion_comercial = Column(SmallInteger, nullable=True, default=0)
    operacion_control = Column(SmallInteger, nullable=True, default=0)
    codigo_resolucion_fk = Column(Integer, nullable=True)
    codigo_moneda_fk = Column(String(10), nullable=True)
    cue = Column(String(200), nullable=True)
    codigo_externo = Column(String(500), nullable=True)
    cadena_codigo_qr = Column(Text, nullable=True)
    genera_costo_promedio = Column(Boolean, nullable=False, default=False)
    guia = Column(String(50), nullable=True)
    codigo_centro_costo_fk = Column(String(20), nullable=True)
    codigo_bodega_fk = Column(String(10), nullable=True)
    codigo_ubicacion_fk = Column(String(20), nullable=True)
    codigo_sede_fk = Column(String(10), nullable=True)
    codigo_temporal_orden_compra = Column(Integer, nullable=True)
    codigo_movimiento_concepto_fk = Column(String(10), nullable=True)
    codigo_impuesto_industria_comercio_fk = Column(String(5), nullable=True)
    vr_base_impuesto_industria_comercio_propuesto = Column(Float, nullable=True, default=0.0)
    vr_base_impuesto_industria_comercio = Column(Float, nullable=True, default=0.0)
    codigo_empresa_fk = Column(Integer, nullable=False)
    codigo_interface = Column(String(20), nullable=True)

    tercero = relationship(Tercero, foreign_keys=[codigo_tercero_fk], backref="movimientos_tercero")

